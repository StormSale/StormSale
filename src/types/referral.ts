/**
 * Two-Tier Referral Tree Architecture & Override Commission Types (#157)
 */

export interface AffiliateReferralRelation {
  /** Recruited sub-affiliate Stellar wallet address (G...) */
  childAddress: string;
  /** Recruited sub-affiliate display alias or name */
  childName: string;
  /** Master recruiter affiliate Stellar wallet address (G...) */
  parentAddress: string;
  /** Master recruiter display alias or name */
  parentName?: string;
  /** Timestamp when the sub-affiliate was bound to the recruiter */
  recruitedAt: string;
  /** Relationship tier (1 = direct recruit of master affiliate) */
  tier: 1 | 2;
  /** Passive override commission percentage earned by master affiliate (e.g. 2.0%) */
  overrideRatePercent: number;
  /** Direct commission percentage earned by selling sub-affiliate (e.g. 8.0%) */
  directCommissionRatePercent: number;
  /** Referral status */
  status: "active" | "paused";
  /** Optional recruiter tracking code / custom tag */
  recruiterTag?: string;
  /** Total sales volume in XLM generated by this sub-affiliate */
  totalSalesVolumeXlm: number;
  /** Direct commissions earned by this sub-affiliate in XLM */
  totalDirectCommissionEarnedXlm: number;
  /** Passive override commissions earned by recruiter in XLM */
  totalOverrideEarnedXlm: number;
  /** Total count of completed conversions/sales driven */
  salesCount: number;
  /** Most recent conversion timestamp */
  lastSaleAt?: string;
}

export interface TwoTierCommissionSplit {
  /** Gross sale amount in XLM */
  saleAmountXlm: number;
  /** Total campaign commission rate percentage (e.g. 10%) */
  totalCommissionRatePercent: number;
  /** Total commission pool in XLM */
  totalCommissionXlm: number;
  /** Direct selling affiliate address */
  sellingAffiliateAddress: string;
  /** Selling affiliate commission percentage (e.g. 8%) */
  sellingAffiliateRatePercent: number;
  /** Selling affiliate earned commission in XLM */
  sellingAffiliateCommissionXlm: number;
  /** Selling affiliate commission in Stroops (10^7) */
  sellingAffiliateStroops: bigint;
  /** Master recruiter affiliate address (if registered) */
  recruiterAddress?: string;
  /** Recruiter override percentage (e.g. 2%) */
  recruiterOverrideRatePercent: number;
  /** Recruiter override commission in XLM */
  recruiterOverrideCommissionXlm: number;
  /** Recruiter override commission in Stroops (10^7) */
  recruiterOverrideStroops: bigint;
  /** Indicates whether a second-tier override recruiter was present */
  hasRecruiter: boolean;
  /** Calculated effective split ratio label, e.g. "80% / 20%" */
  splitRatioLabel: string;
}

export interface ReferralTreeNode {
  /** Stellar address */
  address: string;
  /** Display alias */
  name: string;
  /** Hierarchy level: 0 = Master Root, 1 = Tier-1 Sub-Affiliate, 2 = Tier-2 Sub-Affiliate */
  tier: number;
  /** Role label */
  roleLabel: "Master Affiliate" | "Sub-Affiliate (Tier 1)" | "Sub-Affiliate (Tier 2)";
  /** Direct parent address */
  parentAddress?: string;
  /** Date joined / recruited */
  recruitedAt: string;
  /** Total conversions driven */
  salesCount: number;
  /** Total sales volume driven in XLM */
  salesVolumeXlm: number;
  /** Direct commission earnings in XLM */
  directEarningsXlm: number;
  /** Passive override commission earnings generated for master recruiter in XLM */
  overrideEarningsXlm: number;
  /** Active status */
  isActive: boolean;
  /** Direct child nodes recruited by this affiliate */
  children: ReferralTreeNode[];
}

export interface ReferralTreeSummary {
  /** Master affiliate wallet address */
  masterAddress: string;
  /** Total direct recruited sub-affiliates */
  directRecruitsCount: number;
  /** Total second-tier sub-affiliates */
  secondTierRecruitsCount: number;
  /** Total sub-affiliate network size */
  totalNetworkSize: number;
  /** Cumulative network sales volume in XLM */
  totalNetworkVolumeXlm: number;
  /** Cumulative passive override commission earned in XLM */
  totalOverrideEarnedXlm: number;
  /** Top producing recruited sub-affiliate */
  topPerformer?: {
    address: string;
    name: string;
    volumeXlm: number;
    overrideXlm: number;
  };
  /** Recent override rewards history */
  recentOverrides: {
    id: string;
    subAffiliateAddress: string;
    subAffiliateName: string;
    saleAmountXlm: number;
    overrideEarnedXlm: number;
    timestamp: string;
    txHash?: string;
  }[];
}

export interface RecruiterInvitePayload {
  recruiterAddress: string;
  tag?: string;
  overrideRatePercent?: number;
  createdAt: string;
  signature?: string;
}
