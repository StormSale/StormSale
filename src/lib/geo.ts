const round1 = (n: number) => Math.round(n * 10) / 10;

/** SVG path data for each land ring, projected into the map's viewBox. */
export const WORLD_LAND_PATHS: readonly string[] = LAND_RINGS.map((ring) => {
  let d = "";
  for (let i = 0; i + 1 < ring.length; i += 2) {
    const { x, y } = projectToMap(ring[i + 1], ring[i]);
    d += `${i === 0 ? "M" : "L"}${round1(x)} ${round1(y)}`;
  }
  return `${d}Z`;
});
